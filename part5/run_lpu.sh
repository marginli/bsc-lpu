#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════
# run_lpu.sh — 在 Linux 終端機一次跑完整條管線
#
#   ./run_lpu.sh                      用內建的預設路徑
#   ./run_lpu.sh /path/D03 /path/D06  換一台機器時，把兩個資料目錄傳進來
#
# 也吃環境變數：LPU_D03、LPU_D06、LPU_OUT
#
# 這支腳本做四件事：檢查環境 → 跑完十四條指令 → 核對結果 → 列出產出。
# ═══════════════════════════════════════════════════════════════════════
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

# 命令列參數優先，其次環境變數，最後用 Config 裡的預設值
export LPU_D03="${1:-${LPU_D03:-}}"
export LPU_D06="${2:-${LPU_D06:-}}"
export LPU_OUT="${LPU_OUT:-$HERE/out}"
[ -z "$LPU_D03" ] && unset LPU_D03
[ -z "$LPU_D06" ] && unset LPU_D06

PY="${PYTHON:-python3}"

hr() { printf '%s\n' "════════════════════════════════════════════════════════════════════"; }

# ── 一、環境與資料 ────────────────────────────────────────────────────
hr; echo "第一步：檢查環境與資料"; hr
if ! "$PY" run_lpu.py check; then
  echo
  echo "檢查沒過。缺套件的話："
  echo "    python3 -m pip install --upgrade 'numpy>=1.24' 'scipy>=1.10' 'matplotlib>=3.6'"
  echo "缺資料的話：這條管線需要 D03（分區）與 D06（骨架）兩個目錄，約 280 MB，"
  echo "程式本身搬過去沒有用，資料要一起搬。"
  exit 1
fi

# ── 二、跑 ───────────────────────────────────────────────────────────
# --force-recruit 的意思：
#   指令 9（滾雪球招募）在這份資料上沒有可用的操作區間——20 種參數組合，
#   結果不是「只有種子 1 顆」就是「整池 723 顆」，沒有一種收到一部分。
#   主程式預設會在那裡停下來，不產出看起來完整、其實沒有意義的結果。
#   這裡加上旗標讓它往下走，是為了把後面幾步也跑出來；但要記得，
#   之後每一個數字都建立在「撐大 4 格」這一種讀法上。
echo
hr; echo "第二步：跑完十四條指令"; hr
"$PY" run_lpu.py all --force-recruit

# ── 三、產出 ─────────────────────────────────────────────────────────
echo
hr; echo "第三步：產出"; hr
ls -1sh "$LPU_OUT" | sed 's/^/   /'
echo
echo "完成。圖在 $LPU_OUT/*.png，數字在 $LPU_OUT/*.json。"
